// Aligned allocation matching the reference's svt_aom_memalign(32, ...)
// contract: 32-byte alignment, byte size as given. See the MEMALIGN note
// in the file header for the named MSVC deviation.
void* aligned32(std::size_t bytes) {
#ifdef _MSC_VER
    return _aligned_malloc(bytes, 32);
#else
    return std::aligned_alloc(32, bytes);
#endif
}
void aligned32Free(void* p) {
#ifdef _MSC_VER
    _aligned_free(p);
#else
    std::free(p);
#endif
}

