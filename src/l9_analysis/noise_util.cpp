// 1:1 port of svt_aom_noise_psd_get_default_value (noise_util.c:20-22).
// The int32 block_size promotes to float for the multiply/divide exactly as
// the reference's implicit conversion sequence does; block_size*block_size is
// int arithmetic (<= 1024 at the supported sizes, no overflow) before the
// promotion.
float noisePsdGetDefaultValue(std::int32_t blockSize, float factor) {
    return (factor * factor / 10000) * blockSize * blockSize / 8;
}

// 1:1 port of svt_aom_noise_tx_malloc (noise_util.c:24-68). The SVT_ERROR
// print at :53 is DROPPED (no stderr in the port) - the nullptr return is the
// contract. malloc -> new; memset -> std::memset; svt_aom_memalign(32) ->
// aligned32 below; svt_aom_free -> std::free. The struct memset zero-fills
// every field including the function pointers (:29) before the switch.
NoiseTx* noiseTxMalloc(std::int32_t blockSize) {
    NoiseTx* noiseTx = new (std::nothrow) NoiseTx;
    if (!noiseTx) {
        return nullptr;
    }
    std::memset(noiseTx, 0, sizeof(*noiseTx));
    switch (blockSize) {
    case 2:
        noiseTx->fft  = fft2d2;
        noiseTx->ifft = ifft2d2;
        break;
    case 4:
        noiseTx->fft  = fft2d4;
        noiseTx->ifft = ifft2d4;
        break;
    case 8:
        noiseTx->fft  = fft2d8;
        noiseTx->ifft = ifft2d8;
        break;
    case 16:
        noiseTx->fft  = fft2d16;
        noiseTx->ifft = ifft2d16;
        break;
    case 32:
        noiseTx->fft  = fft2d32;
        noiseTx->ifft = ifft2d32;
        break;
    default:
        delete noiseTx;
        return nullptr;
    }
    noiseTx->block_size = blockSize;
    // svt_aom_memalign(32, 2 * sizeof(float) * block_size * block_size):
    // 8 * blockSize^2 bytes, rounded UP to the alignment multiple (a no-op at
    // every supported size, kept for the contract).
    const std::size_t bytes =
        2 * sizeof(float) * static_cast<std::size_t>(blockSize) *
        static_cast<std::size_t>(blockSize);
    noiseTx->tx_block = static_cast<float*>(aligned32(bytes));
    noiseTx->temp     = static_cast<float*>(aligned32(bytes));
    if (!noiseTx->tx_block || !noiseTx->temp) {
        noiseTxFree(noiseTx);
        return nullptr;
    }
    // Clear the buffers up front. Some outputs of the forward transform are
    // real only (the imaginary component will never be touched) - verbatim
    // noise_util.c:63-66.
    std::memset(noiseTx->tx_block, 0, bytes);
    std::memset(noiseTx->temp, 0, bytes);
    return noiseTx;
}

// 1:1 port of svt_aom_noise_tx_forward (noise_util.c:70-72): one fft call,
// data -> temp workspace, tx_block output.
void noiseTxForward(NoiseTx* noiseTx, const float* data) {
    noiseTx->fft(data, noiseTx->temp, noiseTx->tx_block);
}

// AOMMAX(p, k_eps) - max of two floats, the reference macro's semantics
// (AOMMAX is a macro in definitions.h; the port keeps the same >-based
// max expression, typed float).
float aomMax(float a, float b) { return a > b ? a : b; }

// 1:1 port of svt_aom_noise_tx_filter_c (noise_util.c:74-94).
void noiseTxFilterC(std::int32_t blockSize, float* blockPtr, const float psd) {
    const float kBeta               = 1.1f;
    const float kBetaM1DivKBeta     = (kBeta - 1.0f) / kBeta;
    const float psdMulKBeta         = kBeta * psd;
    const float kEps                = 1e-6f;
    float*      txBlock             = blockPtr;
    for (std::int32_t y = 0; y < blockSize; ++y) {
        for (std::int32_t x = 0; x < blockSize; ++x) {
            const float p = txBlock[0] * txBlock[0] + txBlock[1] * txBlock[1];
            if (p > psdMulKBeta && p > 1e-6) {
                float val = (p - psd) / aomMax(p, kEps);
                txBlock[0] *= val;
                txBlock[1] *= val;
            } else {
                txBlock[0] *= kBetaM1DivKBeta;
                txBlock[1] *= kBetaM1DivKBeta;
            }
            txBlock += 2;
        }
    }
}

// 1:1 port of svt_aom_noise_tx_inverse (noise_util.c:96-102): n = the
// ELEMENT COUNT (block_size^2); ifft then data[i] /= n - the normalization
// lives here (the AN13 finding: ifft2d(fft2d(f)) == n_side^2 * f, so the
// composed forward->inverse is IDENTITY).
void noiseTxInverse(NoiseTx* noiseTx, float* data) {
    const std::int32_t n = noiseTx->block_size * noiseTx->block_size;
    noiseTx->ifft(noiseTx->tx_block, noiseTx->temp, data);
    for (std::int32_t i = 0; i < n; ++i) {
        data[i] /= n;
    }
}

// 1:1 port of svt_aom_noise_tx_free (noise_util.c:104-111): svt_aom_free ->
// aligned32Free, then the struct delete.
void noiseTxFree(NoiseTx* noiseTx) {
    if (!noiseTx) {
        return;
    }
    aligned32Free(noiseTx->tx_block);
    aligned32Free(noiseTx->temp);
    delete noiseTx;
}


